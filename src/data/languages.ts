// Alias for backward compatibility
export const PODCAST_LANGUAGES = STUDY_LANGUAGES;

export function findLanguageByCode(code?: string): StudyLanguage {
  if (!code) return STUDY_LANGUAGES[0];
  const cleanCode = code.toLowerCase().trim();
  const exact = STUDY_LANGUAGES.find((l) => l.code.toLowerCase() === cleanCode);
  if (exact) return exact;

  // Handle mix code variations
  if (cleanCode.includes('mix')) {
    const matchedMix = STUDY_LANGUAGES.find((l) => l.code.toLowerCase().includes('mix') && cleanCode.startsWith(l.prefix.toLowerCase()));
    if (matchedMix) return matchedMix;
  }

  const prefix = cleanCode.split('-')[0];
  const byPrefix = STUDY_LANGUAGES.find((l) => l.prefix.toLowerCase() === prefix);
  return byPrefix || STUDY_LANGUAGES[0];
}

export function findLanguageByName(name?: string): StudyLanguage {
  if (!name) return STUDY_LANGUAGES[0];
  const cleanName = name.toLowerCase().trim();
  const exact = STUDY_LANGUAGES.find(
    (l) => l.name.toLowerCase() === cleanName || l.nativeName.toLowerCase().includes(cleanName)
  );
  if (exact) return exact;

  const partial = STUDY_LANGUAGES.find(
    (l) => cleanName.includes(l.name.toLowerCase()) || l.name.toLowerCase().includes(cleanName)
  );
  return partial || STUDY_LANGUAGES[0];
}

export function getLanguagesByCategory(category: StudyLanguage['category']): StudyLanguage[] {
  return STUDY_LANGUAGES.filter((l) => l.category === category);
}
